"""Export experiment-tracking evidence from MLflow (Task 5 deliverable).

Writes
  reports/tracking/all_runs.csv            every tracked run with provenance tags and key metrics
  reports/tracking/model_comparison.md     comparison table of the model-selection campaign
  reports/tracking/registry.md             registered model version(s) and their lineage
"""

from __future__ import annotations

from pathlib import Path

import mlflow
import pandas as pd

from credit_risk.config import load_config

OUT = Path("reports/tracking")
TAGS = ["run_label", "candidate", "model_family", "data_version", "data_md5", "git_commit", "git_dirty",
        "config_name", "config_sha256", "seed", "change_kind", "train_rows", "test_rows"]
METRICS = ["cv_selection_score", "cv_selection_std", "test_average_precision", "test_roc_auc", "test_recall",
           "test_precision", "test_f1", "test_f2", "test_balanced_accuracy", "test_accuracy", "test_brier",
           "test_threshold", "train_seconds"]


def main() -> int:
    cfg = load_config("configs/full.yaml")
    mlflow.set_tracking_uri(cfg.tracking.tracking_uri)
    client = mlflow.MlflowClient()
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for exp in client.search_experiments():
        for r in client.search_runs([exp.experiment_id], max_results=5000):
            rows.append({"experiment": exp.name, "run_id": r.info.run_id, "run_name": r.info.run_name,
                         "status": r.info.status,
                         "start_time": pd.to_datetime(r.info.start_time, unit="ms"),
                         **{t: r.data.tags.get(t) for t in TAGS},
                         **{m: r.data.metrics.get(m) for m in METRICS},
                         "has_model": any(a.path == "model" for a in client.list_artifacts(r.info.run_id)),
                         "has_config": any(a.path == "config" for a in client.list_artifacts(r.info.run_id))})
    runs = pd.DataFrame(rows).sort_values("start_time")
    runs.to_csv(OUT / "all_runs.csv", index=False)

    sel = runs[(runs["experiment"] == cfg.tracking.experiment_name) &
               (runs["run_label"].isin(["selection"]) | runs["run_label"].str.startswith("ablation"))]
    cols = ["run_label", "candidate", "cv_selection_score", "cv_selection_std", "test_average_precision",
            "test_roc_auc", "test_recall", "test_precision", "test_f2", "test_accuracy", "test_brier", "run_id"]
    lines = ["# Model comparison (generated by scripts/export_tracking.py)", "",
             f"Selection metric: cross-validated PR-AUC on the training split (5 folds). Test split = held-out "
             f"{sel['test_rows'].iloc[0]} customers (data {sel['data_version'].iloc[0]}), scored once per run.", "",
             "| group | candidate | CV PR-AUC (sd) | test PR-AUC | ROC-AUC | recall | precision | F2 | accuracy | "
             "Brier | run |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for _, r in sel[cols].iterrows():
        sd = f" ({r['cv_selection_std']:.3f})" if pd.notna(r["cv_selection_std"]) else ""
        lines.append(f"| {r['run_label']} | {r['candidate']} | {r['cv_selection_score']:.4f}{sd} | "
                     f"{r['test_average_precision']:.4f} | {r['test_roc_auc']:.4f} | {r['test_recall']:.3f} | "
                     f"{r['test_precision']:.3f} | {r['test_f2']:.3f} | {r['test_accuracy']:.3f} | "
                     f"{r['test_brier']:.4f} | `{r['run_id'][:8]}` |")
    by_exp = runs.groupby("experiment").size().to_dict()
    lines += ["", f"**Tracked runs:** {len(runs)} in total ({', '.join(f'{k}: {v}' for k, v in by_exp.items())}). "
              f"Runs with logged model artefact: {int(runs['has_model'].sum())}; with stored config: "
              f"{int(runs['has_config'].sum())}. Full list: `reports/tracking/all_runs.csv`."]
    (OUT / "model_comparison.md").write_text("\n".join(lines) + "\n")

    reg = ["# Model registry (generated by scripts/export_tracking.py)", "",
           "| model | version | aliases | run | candidate | data | git commit | config | created |",
           "|---|---|---|---|---|---|---|---|---|"]
    for rm in client.search_registered_models():
        for mv in client.search_model_versions(f"name='{rm.name}'"):
            t = mv.tags
            reg.append(f"| {rm.name} | {mv.version} | {', '.join(mv.aliases) or '-'} | `{mv.run_id[:8]}` | "
                       f"{t.get('candidate')} | {t.get('data_version')} (`{str(t.get('data_md5'))[:8]}`) | "
                       f"`{str(t.get('git_commit'))[:10]}` | {t.get('config_name')} (`{str(t.get('config_sha256'))[:10]}`) | "
                       f"{pd.to_datetime(mv.creation_timestamp, unit='ms'):%Y-%m-%d %H:%M} |")
    (OUT / "registry.md").write_text("\n".join(reg) + "\n")
    print("\n".join(lines[-1:]))
    print("\n".join(reg))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
