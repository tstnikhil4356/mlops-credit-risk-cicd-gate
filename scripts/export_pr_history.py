"""Export the GitHub pull-request / CI history (Task 6 deliverable) to reports/ci/pr_history.md.

Uses the GitHub CLI (`gh`, authenticated). For every PR: state, head branch, the
quality-gate and baseline-guard check results with links, and the gate summary
comment posted by CI.

Usage: python scripts/export_pr_history.py
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

OUT = Path("reports/ci/pr_history.md")


def gh(*args: str):
    out = subprocess.run(["gh", *args], capture_output=True, text=True, check=True).stdout
    return json.loads(out) if out.strip() else None


def main() -> int:
    repo = gh("repo", "view", "--json", "nameWithOwner,url")
    prs = gh("pr", "list", "--state", "all", "--limit", "50", "--json",
             "number,title,state,headRefName,url,mergedAt,labels,statusCheckRollup")
    prs = sorted(prs, key=lambda p: p["number"])
    lines = [
        "# CI history: pull requests through the quality gate (generated by scripts/export_pr_history.py)",
        "",
        f"Repository: {repo['url']}",
        "",
        "| PR | Title | Branch | Labels | quality-gate | baseline-guard | Final state |",
        "|---|---|---|---|---|---|---|",
    ]
    details = []
    for p in prs:
        checks = {c.get("name"): c for c in p["statusCheckRollup"] or []}

        def fmt(name: str) -> str:
            c = checks.get(name)
            if not c:
                return "-"
            concl = (c.get("conclusion") or c.get("status") or "").lower()
            icon = {"success": "✅ pass", "failure": "❌ fail", "skipped": "⏭ skipped"}.get(concl, concl)
            return f"[{icon}]({c.get('detailsUrl')})" if c.get("detailsUrl") else icon

        state = "merged" if p["mergedAt"] else p["state"].lower()
        labels = ", ".join(lab["name"] for lab in p["labels"]) or "-"
        lines.append(f"| [#{p['number']}]({p['url']}) | {p['title']} | `{p['headRefName']}` | {labels} | "
                     f"{fmt('quality-gate')} | {fmt('baseline-guard')} | {state} |")
        comments = gh("api", f"repos/{repo['nameWithOwner']}/issues/{p['number']}/comments")
        gate = [c["body"] for c in comments if "<!-- quality-gate -->" in c["body"]]
        if gate:
            body = gate[-1].replace("<!-- quality-gate -->", "").strip()
            details += ["", f"## #{p['number']}: {p['title']}", "", body]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines + ["", "---", "# Gate summaries as posted on each PR"] + details) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
