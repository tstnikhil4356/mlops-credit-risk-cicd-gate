"""The ONLY supported way to change baseline/baseline_metrics.json.

Baseline update rule (docs/ci_quality_gate.md):
  1. Run from a clean working tree; the baseline is reproduced by training the
     CI configuration on the currently checked-out code + DVC data.
  2. A written --reason is mandatory and is stored in the file.
  3. The change goes through its own pull request labelled `baseline-update`,
     approved by a CODEOWNER. The baseline-guard CI job re-trains and fails if
     the committed numbers do not match what the PR's code/data reproduce, so a
     hand-edited (e.g. lowered) baseline can never be merged.

Usage:
    python scripts/update_baseline.py --reason "Adopt dataset v2 (drill: docs/data_change_drill.md)"
    python scripts/update_baseline.py --check   # used by CI: verify file matches a fresh run
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import subprocess
import sys
from pathlib import Path

from credit_risk.config import load_config
from credit_risk.train import run_training

GATED_KEYS = ("average_precision", "roc_auc", "recall", "precision", "f2", "threshold")


def _dirty() -> bool:
    out = subprocess.run(["git", "status", "--porcelain", "--untracked-files=no", "--", ".", ":(exclude)reports"], capture_output=True, text=True)
    return bool(out.stdout.strip())


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="configs/ci.yaml")
    ap.add_argument("--reason")
    ap.add_argument("--check", action="store_true", help="Verify the committed baseline is reproducible")
    ap.add_argument("--candidate", help="With --check: reuse a CI run summary instead of re-training")
    ap.add_argument("--allow-dirty", action="store_true")
    args = ap.parse_args()

    cfg = load_config(args.config)
    path = Path(cfg.paths.baseline)

    if args.check:
        committed = json.loads(path.read_text())
        fresh = (json.loads(Path(args.candidate).read_text()) if args.candidate
                 else run_training(cfg, tracking=False))
        problems = []
        for key in GATED_KEYS:
            a, b = committed["metrics"][key], fresh["metrics"][key]
            if abs(a - b) > 1e-6:
                problems.append(f"{key}: committed {a:.6f} but this code/data reproduces {b:.6f}")
        for key in ("data_md5", "config_sha256"):
            if committed.get(key) != fresh.get(key):
                problems.append(f"{key}: committed {committed.get(key)} != reproduced {fresh.get(key)}")
        if problems:
            print("Baseline is NOT reproducible from this commit:\n  - " + "\n  - ".join(problems))
            return 1
        print("Baseline reproduces exactly from this commit's code, config and data.")
        return 0

    if not args.reason:
        ap.error("--reason is required when updating the baseline")
    if _dirty() and not args.allow_dirty:
        sys.exit("Refusing to write a baseline from a dirty working tree: commit your changes first.")

    summary = run_training(cfg, run_label="baseline-update", extra_tags={"baseline_reason": args.reason})
    previous = json.loads(path.read_text()) if path.exists() else None
    record = {
        "_comment": "Generated by scripts/update_baseline.py. Do not edit by hand: CI verifies it.",
        "updated_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "reason": args.reason,
        "previous": ({k: previous.get(k) for k in ("git_commit", "data_version", "updated_at")}
                     | {"average_precision": previous["metrics"]["average_precision"]}) if previous else None,
        **{k: v for k, v in summary.items() if not k.startswith("_") and k != "candidates"},
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(record, indent=2, default=str) + "\n")
    print(f"Baseline written to {path}: {record['selected']} AP={record['metrics']['average_precision']:.4f} "
          f"recall={record['metrics']['recall']:.4f} (data {record['data_version']}, run {record['selected_run_id']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
